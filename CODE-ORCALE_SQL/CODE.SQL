SELECT AA.KH_MAXA, NVL(AA.KU_MATO, '') KU_MATO, AA.KH_MAKH, AA.KU_SCHEM_CD, INITCAP(AA.KH_TENKH) KH_TENKH, AA.KH_NGAYSINH,AA.KH_GIOITINH, AA.KH_CMT, 
        AA.KH_NOICAP, AA.KH_NGAYCAP, AA.KH_NGAYHHCMT, AA.KH_DIACHI, AA.KH_MOBILE, AA.KU_SOKU, AA.KU_CAPQLV, 
        AA.KU_NGAYDHAN_1, AA.KU_NGAYDHAN_2, AA.KU_NGAYDHAN_3, AA.KU_LSUAT, AA.KU_DTTH, AA.KU_MUCVAY, AA.KU_NGUONVON, 
        CASE WHEN GH_TSOTHG > 0 THEN GH_TSOTHG
        ELSE (TO_CHAR(KU_NGAYDHAN_3, 'YYYY')  -  TO_CHAR(KU_NGAYDHAN_1, 'YYYY')) * 12 + 
        (TO_CHAR(KU_NGAYDHAN_3, 'MM')  -  TO_CHAR(KU_NGAYDHAN_1, 'MM')) END SOTHANG_GIAHAN,
        AA.KU_GNGAN, AA.KU_DNOTHAN, AA.KU_DNOQHAN, AA.KU_DNOKHOANH, AA.LAIDATHU, AA.LAITON,AA. KU_LAI_DT,
        AA.KU_LAI_TT, AA.KU_TON_RPA, AA.KU_SPRD_CD, DM_SCHEME.SC_TEN SC_TEN, TEN_PNKT,aa.ku_ngaygndt,aa.ku_ngaygdgn,
        NVL(DECODE(AA.TO_DVUT, 'SEL', '15', AA.TO_DVUT), '15') TO_DVUT, NVL(TOTK.KH_MAKH, ' ') TO_MATT, 
        INITCAP(NVL(AA.TO_TENTT, ' ')) TO_TENTT, NVL(TOTK.KH_DIACHI, ' ') TO_DIACHI, NVL(TOTK.KH_CMT, ' ') TO_CMT,  
        NVL(TOTK.KH_NGAYCAP, NULL) TO_NGAYCAP, NVL(TOTK.KH_NOICAP, ' ') TO_NOICAP, NVL(TOTK.KH_MOBILE, ' ') TO_MOBILE, 
        AA.KU_CHUANNDP, INITCAP(AA.SV_TENSV) SV_TENSV, AA.SV_CMT_SV, AA.SV_NGNHAPHOC, AA.SV_NGRTRUONG, 
        TEN_CAPQLV, TEN_DTTH, XA.TEN TEN_XA, CS_SO_TK2, CS_SODU_TK, CS_M_GUITK, CS_M_RUTTK, NV_GQVL, NVL(SLGN, 0) SLGN,
        SV_MATRUONG , TO_CHAR(KU_NGAYHHKH,'DD/MM/YYYY') KU_NGAYHHKH,AA.KH_LOAIKH, 
        KU_GOCDHAN, KU_MANDT, DT_TENDT,
        (SELECT DISTINCT TEN FROM DMTHON WHERE MA = AA.KH_MADP) AS TENTHON
    FROM
    (            
    SELECT DECODE(SUBSTR(SUBSTR(NVL(TO_MADP, KH_MADP), 1, 6), 1, 4), '3400', --SUBSTR(KU_MAPGD, 3) thay bằng 3400  
                    SUBSTR(NVL(TO_MADP, KH_MADP), 1, 6), SUBSTR(KU_MAPGD, 3) || '00') KH_MAXA, 
        KH_MAKH,KH_LOAIKH, KH_TENKH, KH_NGAYSINH,decode(KH_GIOITINH,'02','Nữ','Nam') KH_GIOITINH, 
        KH_CMT, KH_NOICAP, KH_NGAYCAP, KH_TENVC, KH_CMT_VC, KH_DIACHI, KH_MOBILE, KH_NGAYHHCMT,
        KU_SOKU, KU_MATO,TO_DVUT, TO_TENTT, TO_MATT, KU_SCHEM_CD, KU_NGAYVAY, KU_NGAYDHAN_1, KU_NGAYDHAN_2,
        KU_NGAYDHAN_3, KU_LSUAT, KU_DTTH, KU_NGUONVON, KU_MUCVAY, KU_GNGAN,
        NVL(CV.CV_DNOTHAN, KU_DNOTHAN) KU_DNOTHAN,
        NVL(CV.CV_DNOQHAN, KU_DNOQHAN) KU_DNOQHAN,
        NVL(CV.CV_DNOKHOANH, KU_DNOKHOANH) KU_DNOKHOANH,
        NVL(KU_LAITHAN, 0) + NVL(KU_LAIQHAN, 0) AS LAIDATHU, ku_ngaygndt,ku_ngaygdgn,
        --NVL(KU_LAITONTHAN, 0) + NVL(KU_LAITONQHAN, 0)  - NVL(KU_LCDHAN_DT,0)  AS LAITON, 
        NVL(KU_LAITONTHAN, 0) + NVL(KU_LAITONQHAN, 0) -NVL(KU_LCDHAN_DT,0)  AS LAITON,
        KU_LAI_DT, KU_M_LAI_TT KU_LAI_TT, KU_TON_RPA,  
        KU_SPRD_CD, KU_CAPQLV, SV_TENSV, SV_CMT_SV, SV_NGNHAPHOC, SV_NGRTRUONG, KU_CHUANNDP,KU_MAPNKT51,
        cs.CS_SO_TK2, NVL(cs.CS_SODU_TK, 0) CS_SODU_TK, NVL(cs.CS_M_GUITK, 0) CS_M_GUITK, NVL(cs.CS_M_RUTTK, 0) CS_M_RUTTK,
        CASE WHEN KU_NGUONVON = '1' AND KU_CHTRINH = '03' AND (KU_CAPQLV IS NULL OR KU_CAPQLV IN ('20', '21')) AND
                    (SELECT PL_NGUONVON_BS FROM PLKT WHERE PL_SOKU = KU_SOKU) = '02' THEN 'NHCSXH huy động' 
             WHEN KU_NGUONVON = '1' AND KU_CHTRINH = '03' AND (KU_CAPQLV IS NULL OR KU_CAPQLV = '20') AND 
                    NVL((SELECT PL_NGUONVON_BS FROM PLKT WHERE PL_SOKU = KU_SOKU), 'X') <> '02' THEN 'Qũy QG về việc làm TW'
             WHEN KU_NGUONVON = '1' AND KU_CHTRINH = '03' AND KU_CAPQLV IS NOT NULL AND KU_CAPQLV NOT IN ('20', '21') THEN 'Hội đoàn thể'
             WHEN KU_NGUONVON = '2' AND KU_CHTRINH = '03' AND PM_DEF = 'MANDT_GQVL_TP' THEN 'GQVL vốn TP'
             WHEN KU_NGUONVON = '2' AND KU_CHTRINH = '03' AND PM_DEF = 'MANDT_GQVL' THEN 'GQVL vốn Quận/Huyện'
             WHEN KU_NGUONVON = '2' AND KU_CHTRINH = '03' AND PM_DEF = 'MANDT_NKT' THEN 'Người khuyết tật'
             WHEN KU_NGUONVON = '2' AND ((KU_CHTRINH = '99' AND PM_DEF = 'MANDT_DDGT') OR
                (KU_CHTRINH = '03' AND PM_DEF NOT IN  ('MANDT_GQVL', 'MANDT_GQVL_TP', 'MANDT_NKT'))) THEN 'Di dời, giải tỏa' 
             WHEN KU_NGUONVON = '2' AND KU_CHTRINH = '03' AND PM_DEF IS NULL THEN  '*** KIỂM TRA LẠI ***'
        ELSE NULL
        END NV_GQVL, SLGN, SV_MATRUONG,KU_NGAYHHKH, KU_GOCDHAN, KU_MANDT, KU_TTMONVAY, KH_MADP
    FROM HSKU, 
        (
        SELECT DISTINCT KH_MAKH, KH_TENKH, KH_NGAYSINH, KH_GIOITINH, KH_CMT, KH_NOICAP, KH_NGAYCAP, 
                KH_TENVC, KH_CMT_VC, KH_DIACHI, KH_MOBILE, KH_MADP,KH_LOAIKH, KH_NGAYHHCMT
        FROM HSKH WHERE KH_MAPGD = '00' || :P_MAPOS
        UNION
        SELECT DISTINCT DN_MA, DN_TEN, NULL, NULL, NULL, NULL, NULL, NULL,NULL, DN_DIACHI, DN_MOBILE, DN_MADP ,DN_PLOAI, NULL
        FROM HSKH_DN  WHERE DN_MAPGD = '00' || :P_MAPOS
        ) KH,                                            
        (
        SELECT * FROM HSTO_HISTORY WHERE NG_CAPNHAT = TO_DATE(:P_NGAYBC, 'DD/MM/YYYY') 
        ), 
         
        (
        SELECT * FROM HSSV WHERE SV_REC_ST = 'A'
        ) ,
        (
        SELECT DISTINCT CS_MAKH, CS_SO_TK2, CS_SODU_TK, CS_M_GUITK, CS_M_RUTTK
        FROM CASA_VIEW
        WHERE CS_SODU_TK >= 0 AND CS_SP_TK IN ('105', '145') AND CS_TTSO_TK='A' AND
            CS_NGAYBC = TO_DATE(:P_NGAYBC, 'DD/MM/YYYY') AND CS_MAPGD = '00' || :P_MAPOS 
        ) CS,
         (SELECT KH_SOKU, COUNT(KH_DGNGAN_FLG) SLGN  FROM KHGN WHERE KH_DGNGAN_FLG='P'  GROUP BY KH_SOKU ) SOLANGN,
         (
         SELECT PM_NAME, PM_DEF FROM DNGRPT_PARAMETER WHERE PM_CODE = 'MANDT'
         ) DSNDT,
         (
         SELECT KU_SOKU CV_SOKU,
                MAX(NVL(KU_DNOTHAN, 0)) CV_DNOTHAN,
                MAX(NVL(KU_DNOQHAN, 0)) CV_DNOQHAN,
                MAX(NVL(KU_DNOKHOANH, 0)) CV_DNOKHOANH
         FROM HSCV_DAILY
         WHERE KU_NGAYBC = TO_DATE(:P_NGAYBC, 'DD/MM/YYYY') AND KU_MAPGD = '00' || :P_MAPOS
         GROUP BY KU_SOKU
         ) CV
    WHERE KU_MAKH = KH_MAKH (+) AND KU_MATO = TO_MATO (+) AND 
        KU_SOKU = SV_SOKU(+) AND KU_MAKH = CS_MAKH (+) AND
        KU_SOKU= KH_SOKU (+) AND KU_MANDT = PM_NAME (+) AND KU_SOKU = CV.CV_SOKU(+) AND
        (
            KU_TTMONVAY <> 'CLOSE'
            OR NVL(CV.CV_DNOTHAN, NVL(KU_DNOTHAN, 0)) <> 0
            OR NVL(CV.CV_DNOQHAN, NVL(KU_DNOQHAN, 0)) <> 0
            OR NVL(CV.CV_DNOKHOANH, NVL(KU_DNOKHOANH, 0)) <> 0
        ) AND KU_NGAYBC =  TO_DATE(:P_NGAYBC, 'DD/MM/YYYY') AND KU_MAPGD = '00' || :P_MAPOS
                                 
    ) AA,
    (SELECT KHOA_2, GIATRI TEN_CAPQLV FROM DMKHAC WHERE KHOA_1='19') QLV,
    (SELECT KHOA_2, GIATRI TEN_DTTH FROM DMKHAC WHERE KHOA_1='16') DTTH, 
    (SELECT KHOA_2, GIATRI TEN_PNKT FROM DMKHAC WHERE KHOA_1='25') PNKT,
    (
    SELECT MA || '00' MA, 'XÃ ' || MA || '00' TEN FROM DMHUYEN WHERE SUBSTR(MA, 1, 2) = SUBSTR(:P_MAPOS, 1, 2)
    UNION SELECT MA, TEN FROM DMXA WHERE substr(pgd_ql,3,4) = :P_MAPOS
    ) XA, 
    DM_SCHEME,
    (SELECT * FROM HSKH WHERE KH_MAPGD = '00' || :P_MAPOS) TOTK,
    (SELECT DISTINCT DT_MADT, DT_TENDT FROM HSDT) DT,
    (SELECT SOKU, MAX(NVL(GH_TSOTHG, 0)) GH_TSOTHG FROM HSGH_HISTORY GROUP BY SOKU) HSGH  
    WHERE AA.KU_CAPQLV = QLV.KHOA_2(+) AND AA.KU_DTTH = DTTH.KHOA_2(+) AND AA.KU_MAPNKT51=PNKT.KHOA_2(+) AND
        AA.KH_MAXA = XA.MA (+) AND AA.KU_SCHEM_CD = DM_SCHEME.SC_MA(+) AND  AA.TO_MATT = TOTK.KH_MAKH(+) AND
        (CASE WHEN SUBSTR(:P_XA, 1, 3) <> 'ALL' AND INSTR(:P_XA, ';') > 0 AND  AA.KH_MAXA IN
        (
        SELECT REGEXP_SUBSTR (:P_XA, '[^;]+', 1, LEVEL) TRUONG FROM DUAL CONNECT BY REGEXP_SUBSTR (:P_XA, '[^;]+', 1, LEVEL) IS NOT NULL
        )
         THEN 1 ELSE 0 END) = 
        (CASE WHEN SUBSTR(:P_XA, 1, 3) <> 'ALL' AND INSTR(:P_XA, ';') > 0 THEN 1 ELSE 0 END) AND
        (CASE WHEN :P_TOTRUONG IS NOT NULL AND LENGTH(TRIM(:P_TOTRUONG)) > 0 AND AA.KU_MATO = :P_TOTRUONG THEN 1 ELSE 0 END) = 
        (CASE WHEN :P_TOTRUONG IS NOT NULL AND LENGTH(TRIM(:P_TOTRUONG)) > 0 THEN 1 ELSE 0 END) AND
        (CASE WHEN :P_CHTRINH IS NOT NULL AND LENGTH(TRIM(:P_CHTRINH)) > 0 AND 
                            :P_CHTRINH <> '00' AND SUBSTR(AA.KU_SCHEM_CD, 3, 2) = :P_CHTRINH THEN 1 ELSE 0 END) =
        (CASE WHEN :P_CHTRINH IS NOT NULL AND LENGTH(TRIM(:P_CHTRINH)) > 0 AND :P_CHTRINH <> '00' THEN 1 ELSE 0 END) AND
        NVL(DECODE(AA.TO_DVUT, 'SEL', '15', AA.TO_DVUT), '15') = 
        (CASE WHEN :P_LOAISK = 3 THEN '15' ELSE NVL(DECODE(AA.TO_DVUT, 'SEL', '15', AA.TO_DVUT), '15') END) AND
        KU_MANDT=DT.DT_MADT(+) AND KU_SOKU = HSGH.SOKU(+)  AND
        (
            AA.KU_TTMONVAY <> 'CLOSE'
            OR NVL(AA.KU_DNOTHAN, 0) <> 0
            OR NVL(AA.KU_DNOQHAN, 0) <> 0
            OR NVL(AA.KU_DNOKHOANH, 0) <> 0
        )
    ORDER BY AA.KH_MAXA, AA.KU_MATO, AA.KH_MAKH, AA.KU_SCHEM_CD ;