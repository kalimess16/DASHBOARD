SELECT KU_SCHEM_CD MACTVAY
    , (SELECT SC_TEN FROM DM_SCHEME WHERE KU_SCHEM_CD = SC_MA) TENCVAY
    , (SELECT SC_TENVT FROM DM_SCHEME WHERE KU_SCHEM_CD = SC_MA) TEN_RGCVAY
    , SUM(KU_DNOTHAN + KU_DNOQHAN + KU_DNOKHOANH) DUNO_2025
    , SUM(KU_DNOQHAN) NQHAN_2025
    , SUM(KU_DNOKHOANH) DNKHOANH_2025
FROM HSKU
WHERE KU_NGAYBC = '31-DEC-25'
GROUP BY KU_SCHEM_CD
ORDER BY 1;