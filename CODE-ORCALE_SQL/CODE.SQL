SELECT DISTINCT aa.KU_MAKH MAKH, KH_TENKH TENKH, AA.KU_SOKU SOKU, AA.KU_NGAYVAY NGAYVAY
    , BB.NGDHAN_1 NGDHAN_1, BB.GOCDHAN_1 GOCDHAN_1
    , BB.NGDHAN_2 NGDHAN_2, BB.GOCDHAN_2 GOCDHAN_2
    , (KU_DNOTHAN + KU_DNOQHAN + KU_DNOKHOANH) DUNO, SOKYCON
FROM HSKU AA
LEFT JOIN HSKH ON KU_MAKH = KH_MAKH AND KH_TTRANG = 'A' AND KH_MAPGD = KH_MAPGD
LEFT JOIN (
SELECT KH_SOKU,
       MAX(CASE WHEN rn = 1 THEN KH_NGDHAN END) NGDHAN_1,
       MAX(CASE WHEN rn = 1 THEN KH_GOCDHAN END) GOCDHAN_1,
       MAX(CASE WHEN rn = 2 THEN KH_NGDHAN END) NGDHAN_2,
       MAX(CASE WHEN rn = 2 THEN KH_GOCDHAN END) GOCDHAN_2
FROM (
    SELECT T.KH_SOKU, KH_NGDHAN, KH_GOCDHAN,
           ROW_NUMBER() OVER (
               PARTITION BY KH_SOKU
               ORDER BY KH_NGDHAN DESC
           ) AS rn
    FROM KHTN t
    WHERE KH_NGDHAN >= TO_DATE(:P_NGAYBC, 'DD/MM/YYYY')
)
WHERE rn <= 2
GROUP BY KH_SOKU
) BB ON BB.KH_SOKU = AA.KU_SOKU
LEFT JOIN (
SELECT DISTINCT KH_SOKU, COUNT(KH_SOKU) SOKYCON
    FROM KHTN
    WHERE KH_MAPGD = '003430'
    GROUP BY KH_SOKU
    ORDER BY 1
) CC ON CC.KH_SOKU = KU_SOKU
WHERE KU_NGAYBC = '28-FEB-26'
AND KU_TTMONVAY <> 'CLOSE'
AND KU_MAPGD = '003430'
AND KU_CHTRINH = '12'
AND KU_SPRD_CD NOT IN ('121SL2', '121ML2', '121LL2')
ORDER BY 1, 2;
